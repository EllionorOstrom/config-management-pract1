#!/bin/sh
# Задача 1: Вывести отсортированный список имён пользователей из /etc/passwd
# Символ-значение: grep - команда поиска; -o - только совпавшая часть; ^ - начало строки; [^:] - любой символ кроме двоеточия; * - 0 или более раз; /etc/passwd - файл пользователей; | - конвейер (передаёт вывод одной команды на вход другой); sort - сортировка по алфавиту
grep -o '^[^:]*' /etc/passwd | sort


#!/bin/sh
# Задача 2: вывести 5 протоколов с самыми большими номерами портов

# awk '{print $2, $1}' — меняет местами номер и название протокола
# sort -rn — сортирует по номеру по убыванию
# head -5 — оставляет первые 5 строк
awk '{print $2, $1}' /etc/protocols | sort -rn | head -5


#!/bin/sh
# Задача 3: вывести текст в рамке, длина рамки зависит от длины текста

# $1 — текст, переданный как аргумент
text="$1"
# ${#text} — длина текста
len=${#text}
# создаём строку из дефисов нужной длины (len + 2 для пробелов по бокам)
line=$(printf '%*s' "$((len + 2))" '' | tr ' ' '-')

echo "+${line}+"
echo "| ${text} |"
echo "+${line}+"


#!/bin/sh
# Задача 4: вывести все идентификаторы из файла C/C++ без повторений

# $1 — имя файла, переданное как аргумент
# grep -oE — ищет слова по шаблону, выводит только совпадения
# sort -u — сортирует и убирает повторы
grep -oE '\b[a-zA-Z_][a-zA-Z0-9_]*\b' "$1" | sort -u


#!/bin/sh
# Задача 5: зарегистрировать команду — дать права и скопировать в /usr/local/bin

# проверяем, что передан ровно один аргумент
if [ $# -ne 1 ]; then
    echo "Использование: $0 <файл>"
    exit 1
fi

file="$1"
# даём право на исполнение
chmod +x "$file"
# копируем в системную папку команд
cp "$file" /usr/local/bin/
echo "Команда $file зарегистрирована"


#!/bin/sh
# Задача 6: проверить наличие комментария в первой строке файлов .c, .js, .py

# перебираем все файлы нужных расширений
for file in *.c *.js *.py; do
    # пропускаем, если файла нет
    [ -f "$file" ] || continue

    # берём первую строку
    first=$(head -n 1 "$file")

    # проверяем, начинается ли строка с комментария
    case "$first" in
        //*|/\**|\#*) echo "$file: комментарий есть" ;;
        *) echo "$file: комментария нет" ;;
    esac
done


#!/bin/sh
# Задача 7: найти файлы-дубликаты по содержимому

# $1 — путь к каталогу, по умолчанию текущий
dir="${1:-.}"

# md5sum считает хеш; одинаковые хеши = одинаковое содержимое
find "$dir" -type f -exec md5sum {} + | sort | uniq -w32 -D


#!/bin/sh
# Задача 8: архивировать все файлы с указанным расширением

# $1 — каталог, $2 — расширение
dir="$1"
ext="$2"
archive="archive_${ext}.tar"

# ищем файлы по расширению и архивируем
find "$dir" -maxdepth 1 -name "*.$ext" -print0 | tar --null -cvf "$archive" --files-from=-
echo "Создан архив $archive"


#!/bin/sh
# Задача 9: заменить 4 пробела на табуляцию

# $1 — входной файл, $2 — выходной
in="$1"
out="$2"

# sed заменяет 4 пробела на \t (табуляция)
